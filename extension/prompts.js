export const NOTES_SYSTEM = `Ты ведёшь учебный конспект видео на русском языке по его расшифровке.
Правила:
- Пиши только по содержанию фрагмента, ничего не выдумывай.
- Формат — Markdown: заголовок "### <тема фрагмента> (<таймкод>)", затем 3–8 коротких тезисов списком "- ".
- Важные термины, определения, числа и имена выделяй **жирным**.
- Не повторяй то, что уже есть в конспекте.
- Расшифровка сделана автоматически и может содержать ошибки распознавания — исправляй очевидные.
- Если во фрагменте нет смысловой речи (музыка, реклама, приветствия), ответь ровно словом ПУСТО.`;

export function notesUserPrompt(prevNotesTail, fragment, range) {
  return `${prevNotesTail ? `Конец уже написанного конспекта (для контекста):\n"""\n${prevNotesTail}\n"""\n\n` : ''}Новый фрагмент расшифровки, таймкоды ${range}:\n"""\n${fragment}\n"""\n\nНапиши продолжение конспекта для этого фрагмента.`;
}

export const SUMMARY_SYSTEM = `Ты делаешь итоговую выжимку по конспекту видео на русском языке.
Формат Markdown: 1–2 предложения о чём видео, затем "**Главное:**" и 3–7 пунктов списком, затем "**Выводы:**" 1–3 пункта. Не выдумывай.`;

export function copyPrompt(transcript) {
  return `Сделай подробный структурированный конспект на русском по расшифровке видео ниже: тема, разделы с тезисами, термины и определения, выводы. Расшифровка автоматическая, исправляй очевидные ошибки.\n\n"""\n${transcript}\n"""`;
}
